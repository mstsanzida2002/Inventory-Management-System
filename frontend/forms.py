def parse_line_items(raw_json, min_quantity=1):
    """Returns (items, errors); items carry real Product instances."""
    # Assumption: productLabel is a product pk string, not a display name.
    try:
        raw_items = json.loads(raw_json or "[]")
    except (ValueError, TypeError):
        return [], ["Line items could not be read. Please try again."]

    if not isinstance(raw_items, list) or not raw_items:
        return [], ["At least one line item is required."]

    errors = []
    parsed = []
    for index, raw in enumerate(raw_items, start=1):
        if not isinstance(raw, dict):
            errors.append(f"Line {index}: malformed line item.")
            continue

        try:
            product = Product.objects.get(pk=raw.get("productLabel"), is_active=True)
        except (Product.DoesNotExist, ValueError, TypeError):
            errors.append(f"Line {index}: product is invalid or no longer active.")
            continue

        try:
            quantity = int(raw.get("quantity"))
        except (TypeError, ValueError):
            quantity = None
        if quantity is None or quantity < min_quantity:
            errors.append(f"Line {index}: quantity must be at least {min_quantity}.")
            continue

        try:
            unit_price = Decimal(str(raw.get("unitPrice")))
        except (InvalidOperation, TypeError, ValueError):
            unit_price = None
        if unit_price is None or unit_price < 0:
            errors.append(f"Line {index}: unit price cannot be negative.")
            continue

        try:
            discount = Decimal(str(raw.get("discount") or 0))
        except InvalidOperation:
            errors.append(f"Line {index}: discount must be numeric.")
            continue
        if discount < 0:
            errors.append(f"Line {index}: discount cannot be negative.")
            continue

        # Rule: tax always comes from Product.tax_rate -- never the client.
        tax = product.tax_rate

        parsed.append({
            "product": product, "quantity": quantity,
            "unit_price": unit_price, "discount": discount, "tax": tax,
        })

    return parsed, errors


class PurchaseOrderForm(forms.ModelForm):
    """Header fields only -- line items arrive separately as items_json."""

    class Meta:
        model = PurchaseOrder
        fields = ["supplier", "expected_delivery", "notes"]

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.fields["expected_delivery"].required = False
        self.fields["notes"].required = False
        # Security: supplier queryset restricted to active.
        self.fields["supplier"].queryset = Supplier.objects.filter(is_active=True)

    def clean_expected_delivery(self):
        # Rule: order_date is always today, so this is one real-world check.
        expected_delivery = self.cleaned_data.get("expected_delivery")
        if expected_delivery and expected_delivery < timezone.localdate():
            raise forms.ValidationError("Expected delivery date cannot be in the past.")
        return expected_delivery


