# Rule: status is a form-only field, consumed by the view to set is_active.
STATUS_CHOICES = [("Active", "Active"), ("Inactive", "Inactive")]


class ProductForm(forms.ModelForm):

    class Meta:
        model = Product
        fields = [
            "name", "sku", "barcode", "category", "supplier", "brand",
            "unit", "purchase_price", "selling_price", "tax_rate", "reorder_level",
        ]

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        # Rule: sku auto-generates if left blank -- see clean_sku().
        self.fields["sku"].required = False
        self.fields["barcode"].required = False
        self.fields["unit"].required = False
        self.fields["reorder_level"].required = False
        # Security: category/supplier queryset restricted to active, not just the UI.
        self.fields["category"].queryset = Category.objects.filter(is_active=True)
        self.fields["supplier"].queryset = Supplier.objects.filter(is_active=True)

    def clean_sku(self):
        sku = (self.cleaned_data.get("sku") or "").strip()
        if sku:
            return sku
        # Rule: flags this instance so Product.save() retries only on a real collision.
        self.instance._sku_autogenerated = True
        return self.instance._generate_sku()

    def clean_barcode(self):
        barcode = (self.cleaned_data.get("barcode") or "").strip()
        return barcode or None

    def clean_unit(self):
        return self.cleaned_data.get("unit") or UnitOfMeasurement.PIECE

    def clean_reorder_level(self):
        # Rule: blank falls back to the admin-configured default, not the model's own.
        value = self.cleaned_data.get("reorder_level")
        return value if value is not None else SystemSettings.get_settings().default_reorder_level

    def clean_purchase_price(self):
        value = self.cleaned_data.get("purchase_price")
        if value is not None and value < 0:
            raise forms.ValidationError("Purchase price cannot be negative.")
        return value

    def clean_selling_price(self):
        value = self.cleaned_data.get("selling_price")
        if value is not None and value < 0:
            raise forms.ValidationError("Selling price cannot be negative.")
        return value

    def clean_tax_rate(self):
        # Assumption: required, so value is never None here -- no blank-to-0 fallback.
        value = self.cleaned_data.get("tax_rate")
        if value < 0:
            raise forms.ValidationError("Tax rate cannot be negative.")
        return value

