class AdjustmentForm(forms.ModelForm):
    """Rule: product queryset is NOT restricted to is_active -- correcting a
    stale count on a deactivated product is legitimate."""

    class Meta:
        model = InventoryAdjustment
        fields = ["product", "adjustment_type", "quantity", "reason_code", "reason"]

    def clean_quantity(self):
        # Rule: 0 is technically valid but a no-op -- rejected as meaningless.
        value = self.cleaned_data.get("quantity")
        if value is not None and value <= 0:
            raise forms.ValidationError("Quantity must be greater than zero.")
        return value


